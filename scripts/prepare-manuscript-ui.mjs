// Build-time asset preparation only; no per-frame styling or image generation.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { resolve } from 'node:path'
import { ICONS, iconSvg } from './manuscript-icons.mjs'

const root = fileURLToPath(new URL('../', import.meta.url))
export const manifest = JSON.parse(readFileSync(resolve(root, 'assets/ui/manuscript/manifest.json'), 'utf8'))
const assetRoot = '../../../assets/ui/manuscript'
const cssRule = (selectors, body) => selectors.map(s => '.medieval-hud ' + s).join(',\n') + ' { ' + body + ' }\n'

// Normalized source rectangles become a background viewport. Its own aspect
// ratio must be preserved; blindly using cover in a portrait cuts off subjects.
export function cropPresentation(rect, sourceAspect) {
  const [x, y, width, height] = rect
  if (![...rect, sourceAspect].every(Number.isFinite) || sourceAspect <= 0 || x < 0 || y < 0 || width <= 0 || height <= 0 || x + width > 1.000001 || y + height > 1.000001) throw new Error('Invalid artwork crop')
  const number = value => Number(value.toFixed(6))
  return {
    width, height, centerX: x + width / 2, centerY: y + height / 2,
    ratio: number(sourceAspect * width / height),
    size: `${number(100 / width)}% ${number(100 / height)}%`,
    position: `${number(width === 1 ? 0 : 100 * x / (1 - width))}% ${number(height === 1 ? 0 : 100 * y / (1 - height))}%`,
  }
}

export function sceneAspect(id) {
  if (!manifest.scenes.includes(manifest.aliases[id] ?? id)) throw new Error('Unknown scene')
  return manifest.imageSizes.wide[0] / manifest.imageSizes.wide[1]
}

const cropVariables = (name, rect, aspect) => {
  const crop = cropPresentation(rect, aspect)
  return `--${name}-ratio: ${crop.ratio}; --${name}-size: ${crop.size}; --${name}-position: ${crop.position}; --${name}-width: ${crop.width}; --${name}-height: ${crop.height}; --${name}-center-x: ${crop.centerX}; --${name}-center-y: ${crop.centerY};`
}

