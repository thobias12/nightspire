export function assetCss() {
  let css = '/* Generated by scripts/prepare-manuscript-ui.mjs. Edit the manifest or bindings, then regenerate. */\n'
  for (const id of [...manifest.scenes, ...Object.keys(manifest.aliases)]) {
    const canonical = manifest.aliases[id] ?? id
    const aspect = sceneAspect(canonical)
    const image = `url('${assetRoot}/building/${canonical}.webp')`
    const card = `url('${assetRoot}/card/${canonical}.webp')`
    const cardAspect = manifest.imageSizes.card[0] / manifest.imageSizes.card[1]
    css += cssRule([`[data-art-slot="build-${id}"]`, `[data-ui-asset="building-header:${id}"]`, `[data-ui-asset="building-icon:${id}"]`], `--scene-art: ${image}; --card-art: ${card}; --scene-aspect: ${aspect}; ${cropVariables('building', manifest.titleCrop, cardAspect)} background-image: ${image}; background-size: contain; background-position: center; background-repeat: no-repeat;`)
  }
  for (const name of manifest.portraits) {
    css += cssRule([`[data-ui-asset="portrait:${name}"]`], `--portrait-art: url('${assetRoot}/portrait/${name}.webp'); ${cropVariables('portrait', manifest.portraitCrop, 307 / 512)} background-image: var(--portrait-art); background-size: contain; background-position: center;`)
  }
  for (const [selector, name] of Object.entries(iconBindings)) {
    css += cssRule([selector], `background-image: url('${assetRoot}/icon/${name}.svg'); background-size: contain; background-position: center; background-repeat: no-repeat; background-color: transparent; border: 0; box-shadow: none;`)
  }
  return css
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  mkdirSync(resolve(root, 'assets/ui/manuscript/icon'), { recursive: true })
  for (const name of Object.keys(ICONS)) writeFileSync(resolve(root, `assets/ui/manuscript/icon/${name}.svg`), iconSvg(name))
  writeFileSync(resolve(root, 'src/game/ui/ManuscriptAssets.css'), assetCss())
  console.log(`Prepared ${Object.keys(ICONS).length} original vector emblems and dedicated card/wide bindings.`)
}
